def test_envfile_write_keeps_unknown_keys_comments_and_order(tmp_path):
    env_file = tmp_path / ".env"
    original = "# keep me\nUNKNOWN_A=1\n\nOPP_CHANNEL=@old\n# trailer\nUNKNOWN_B='x y'\n"
    env_file.write_text(original, encoding="utf-8")
    inode = env_file.stat().st_ino

    result = envfile.write(env_file, {"OPP_CHANNEL": "@new", "ADMIN_TG_ID": 42, "SKIPPED": None})

    assert env_file.read_text(encoding="utf-8") == (
        "# keep me\nUNKNOWN_A=1\n\nOPP_CHANNEL=@new\n# trailer\nUNKNOWN_B='x y'\nADMIN_TG_ID=42\n"
    )
    assert env_file.stat().st_ino == inode  # in place: a bind-mounted single file stays attached
    backups = sorted(tmp_path.glob(".env.bak-*"))
    assert len(backups) == 1 and backups[0].read_text(encoding="utf-8") == original
    assert result == {"UNKNOWN_A": "1", "OPP_CHANNEL": "@new", "UNKNOWN_B": "x y", "ADMIN_TG_ID": "42"}


def test_envfile_write_rewrites_duplicates_and_creates_file(tmp_path):
    env_file = tmp_path / ".env"
    assert envfile.write(env_file, {"A": "1"}) == {"A": "1"}
    env_file.write_text("A=1\nA=2\n", encoding="utf-8")
    envfile.write(env_file, {"A": "3"})
    assert env_file.read_text(encoding="utf-8") == "A=3\nA=3\n"


def test_envfile_keeps_last_five_backups(tmp_path):
    env_file = tmp_path / ".env"
    env_file.write_text("A=1\n", encoding="utf-8")
    for i in range(7):
        (tmp_path / f".env.bak-2020010{i}-000000").write_text("old\n", encoding="utf-8")
    envfile.write(env_file, {"A": "2"})
    backups = sorted(p.name for p in tmp_path.glob(".env.bak-*"))
    assert len(backups) == envfile.BACKUPS_KEPT == 5
    assert ".env.bak-20200100-000000" not in backups  # oldest dropped
    assert (tmp_path / backups[-1]).read_text(encoding="utf-8") == "A=1\n"  # newest = pre-write content


@pytest.mark.parametrize("updates", [{"A": "x\nB=1"}, {"A": "x\r"}, {"BAD KEY": "1"}, {"A=B": "1"}])
def test_envfile_write_rejects_injection(updates, tmp_path):
    env_file = tmp_path / ".env"
    env_file.write_text("A=1\n", encoding="utf-8")
    with pytest.raises(ValueError):
        envfile.write(env_file, updates)
    assert env_file.read_text(encoding="utf-8") == "A=1\n"


def test_envfile_read_matches_legacy_parser(tmp_path):
    env_file = tmp_path / ".env"
    env_file.write_text(" A = \"q\" \nB='s'\n#C=1\nD=v # not a comment\nnoeq\nE=a=b\n", encoding="utf-8")
    assert envfile.read(env_file) == {"A": "q", "B": "s", "D": "v # not a comment", "E": "a=b"}


