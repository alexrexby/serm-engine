def test_alerts_fall_back_to_env_file(monkeypatch, tmp_path):
    # M3: alerts used to read only the process env; now the .env file is a fallback too
    from core import alerts
    env_file = tmp_path / ".env"
    env_file.write_text(f"SERM_TG_BOT_TOKEN={TOKEN_B}\nTELEGRAM_ADMIN_ID=777\n", encoding="utf-8")
    monkeypatch.setattr(settings.Settings, "env_path", env_file)
    assert alerts.get_bot_token() == TOKEN_B
    assert alerts.get_admin_id() == 777
    monkeypatch.setenv("OPP_BOT_TOKEN", TOKEN_A)
    assert alerts.get_bot_token() == TOKEN_A
    env_file.write_text("ADMIN_TG_ID=not-a-number\n", encoding="utf-8")
    assert alerts.get_admin_id() is None
