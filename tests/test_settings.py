ALL_ENV_NAMES = sorted({
    name for field in settings.Settings.model_fields for name in settings._env_names(field)
})


def _value(v):
    return v.get_secret_value() if hasattr(v, "get_secret_value") else v


@pytest.fixture(autouse=True)
def clean_env(monkeypatch):
    for name in ALL_ENV_NAMES:
        monkeypatch.delenv(name, raising=False)


def _load(tmp_path, text=None):
    env_file = tmp_path / ".env"
    if text is not None:
        env_file.write_text(text, encoding="utf-8")
    return settings.load_settings(env_file=env_file)


def test_legacy_names_count():
    assert len(LEGACY_ENV) == 17


@pytest.mark.parametrize("name", sorted(LEGACY_ENV))
def test_legacy_name_from_process_env(name, monkeypatch, tmp_path):
    field, raw, expected = LEGACY_ENV[name]
    monkeypatch.setenv(name, raw)
    assert _value(getattr(_load(tmp_path), field)) == expected


@pytest.mark.parametrize("name", sorted(LEGACY_ENV))
def test_legacy_name_from_env_file(name, tmp_path):
    field, raw, expected = LEGACY_ENV[name]
