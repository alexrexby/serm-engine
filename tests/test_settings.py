BAD_FORMATS = [
    ("OPP_BOT_TOKEN", "bot_token", "not-a-token"),
    ("OPP_CHANNEL", "channel", "no_at_sign"),
    ("OPP_CONTACT", "contact", "contact_without_at"),
    ("SERM_VK_OWNER_ID", "vk_owner_id", "abc"),
    ("POLZA_BASE_URL", "llm_base_url", "api.example.test"),
]


@pytest.mark.parametrize("name,field,value", BAD_FORMATS)
def test_bad_format_is_a_warning_not_a_crash(name, field, value, tmp_path, caplog):
    # the old code accepted any value: prod must keep starting
    with caplog.at_level("WARNING", logger="Settings"):
        s = _load(tmp_path, f"{name}={value}\n")
    assert _value(getattr(s, field)) == value  # kept as is
    assert any(name in w for w in s.warnings())
    assert all(value not in w for w in s.warnings())  # values (possibly secrets) are not echoed
    assert value not in caplog.text


