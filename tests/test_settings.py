def test_current_env_file_loads(tmp_path):
    # Shape of an installation .env: admin-panel header, quotes, empty values, unknown keys
    lines = ["# Auto-generated by SERM Secrets Admin Panel"]
    for i, (name, (_, raw, _)) in enumerate(sorted(LEGACY_ENV.items())):
        quote = ('"', "'", "")[i % 3]
        lines.append(f"{name}={quote}{raw}{quote}")
    lines += ["SOME_UNKNOWN_KEY=whatever", "EMPTY_KNOWN=", "SERM_PROFILE=", ""]
    s = _load(tmp_path, "\n".join(lines))
    for name, (field, raw, expected) in LEGACY_ENV.items():
        if name in ("ADMIN_PASSWORD", "TELEGRAM_ADMIN_ID"):
            continue  # aliases lose to the canonical name present in the same file
        assert _value(getattr(s, field)) == expected, name
    assert s.profile is None


def test_empty_values_in_file_as_before(tmp_path):
    names = "\n".join(f"{n}=" for n in LEGACY_ENV) + "\n"
    s = _load(tmp_path, names)
    # old code: env.get("OPP_CHANNEL", default) -> "" when the key is present but empty
    assert (s.channel, s.contact, s.active_campaign) == ("", "", "")
    # everything else empty = unset (old `or` chains, int(os.getenv("ADMIN_PORT", "8180")))
    assert s.bot_token.get_secret_value() == ""
    assert s.admin_port == 8180
    assert s.admin_host == "127.0.0.1"
    assert s.llm_base_url == settings.DEFAULT_LLM_BASE_URL
    assert s.admin_tg_id is None


